#!/usr/bin/env python3
"""Build the routing run sheet from evals/triggers/prompts.json and heldout.json.

  python3 scripts/routing_sheet.py --write    writes evals/triggers/run-sheet.md
  python3 scripts/routing_sheet.py --stdout   prints it (used by the sync test)

One row per prompt, in a fixed order. The sheet is a checklist: paste each prompt into a fresh
chat with the plugins installed, note which skill answered, and mark Pass or Miss.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TRIG = ROOT / "evals" / "triggers"


def build():
    main = json.loads((TRIG / "prompts.json").read_text(encoding="utf-8"))
    held = json.loads((TRIG / "heldout.json").read_text(encoding="utf-8"))
    lines = ["# Routing run sheet", "",
             "Generated by `scripts/routing_sheet.py`. Do not edit by hand. Open a fresh chat for each row, "
             "paste the prompt, and write down the skill that answered. Pass means it is in Expected. "
             "For rows with no Expected skill, Pass means no PMM skill answered.", ""]
    for title, rows in (("Set A: prompts.json (direct, indirect, near-miss)", main["prompts"] + main["non_pmm"]),
                        ("Set B: heldout.json (not blind: situation, judgement)", held["prompts"] + held["non_pmm"])):
        lines += [f"## {title}", "", "| # | Kind | Expected | Prompt | Answered | Pass |", "|---|---|---|---|---|---|"]
        for i, r in enumerate(rows, 1):
            exp = ", ".join(r["expect"]) or "(no PMM skill)"
            lines.append(f"| {i} | {r.get('kind', 'non-pmm')} | {exp} | {r['prompt'].replace('|', '/').replace(chr(10), ' ')} | | |")
        lines.append("")
    return "\n".join(lines)


if __name__ == "__main__":
    out = build()
    if "--write" in sys.argv:
        (TRIG / "run-sheet.md").write_text(out, encoding="utf-8")
    else:
        sys.stdout.write(out)
